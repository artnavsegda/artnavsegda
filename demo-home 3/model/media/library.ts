export interface Playlist { id: string; title: string; sub: string; art: string; tracks: Content[] }
const pl = (id: string, title: string, sub: string, tracks: [string, string, number][]): Playlist => ({
  id, title, sub, art: id, tracks: tracks.map(([t, a, d], i) => ({ kind: 'track', id: `${id}-${i}`, title: t, sub: a, art: id, dur: d }))
});
